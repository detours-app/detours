// Render the reader-facing guide from the maintained Markdown source, without a CDN.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { createRequire } from 'node:module';

const require = createRequire(import.meta.url);
const MarkdownIt = require('../PreviewAssets/vendor/markdown-it.min.js');
const docs = new URL('../docs/', import.meta.url);
const markdown = new MarkdownIt({ html: false });
const escape = markdown.utils.escapeHtml;
const source = readFileSync(new URL('USER_GUIDE.md', docs), 'utf8').replace(/^<!--[^]*?-->\s*/, '');
const tokens = markdown.parse(source, {});
const headings = [];
const ids = new Set();
for (let index = 0; index < tokens.length; index++) {
  const token = tokens[index];
  if (token.type !== 'heading_open') continue;
  const title = tokens[index + 1].content;
  const base = title.toLowerCase().replace(/[^a-z0-9\s-]/g, '').replace(/\s+/g, '-');
  let id = base;
  let suffix = 0;
  while (ids.has(id)) id = `${base}-${++suffix}`;
  ids.add(id);
  token.attrSet('id', id);
  headings.push({ id, title, level: Number(token.tag.slice(1)) });
}
const toc = headings.filter(({ level, id }) => level === 2 || ['quick-open-cmd-p', 'supported-remote-hosts'].includes(id))
  .map(({ id, title, level }) => `<a${level === 3 ? ' class="toc-sub"' : ''} href="#${id}">${escape(title)}</a>`).join('\n');
const png = (url) => {
  const bytes = readFileSync(url);
  if (bytes.subarray(0, 8).toString('hex') !== '89504e470d0a1a0a') throw new Error(`Not a PNG: ${url}`);
  return `data:image/png;base64,${bytes.toString('base64')}`;
};
let body = markdown.renderer.render(tokens, markdown.options, {});
body = body.replace(/<p><img src="([^"]+)" alt="([^"]*)"><\/p>/g, (_, path, alt) =>
  `<figure class="figure"><img src="${png(new URL(path, docs))}" alt="${alt}" loading="lazy"><figcaption>${alt}</figcaption></figure>`);
body = body.replaceAll('<table>', '<div class="table-scroll"><table>').replaceAll('</table>', '</table></div>');
body = body.replace(/href="(?!https?:|#)([^"]+)"/g, (_, path) => {
  if (!existsSync(new URL(path.split('#')[0], docs))) throw new Error(`Missing guide link: ${path}`);
  return `href="https://github.com/detours-app/detours/blob/main/resources/docs/${path}"`;
});
const css = readFileSync(new URL('user-guide.css', docs), 'utf8');
const html = `<!doctype html>
<!-- Generated by render-user-guide.mjs. Edit USER_GUIDE.md or user-guide.css, then regenerate. -->
<!-- lint-ignore: max-lines -- generated single-page manual with embedded screenshots for offline reading. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta name="description" content="The Detours user guide: navigation, previews, file operations, SSH hosts, settings and keyboard shortcuts.">
<title>Detours User Guide</title>
<style>${css}</style>
</head>
<body>
<a class="skip" href="#guide">Skip to guide</a>
<header class="topbar"><div class="topbar-inner">
<a class="brand" href="#detours-user-guide"><img src="${png(new URL('../icons/DeepSeaDock.png', docs))}" alt="" width="52" height="52">Detours</a>
<nav aria-label="Project"><a href="https://github.com/detours-app/detours">GitHub</a><a href="#keyboard-shortcuts-reference">Shortcuts</a></nav>
</div></header>
<div class="layout">
<aside class="contents"><p class="eyebrow">User guide</p><nav aria-label="Contents">${toc}</nav></aside>
<main id="guide">
<details class="mobile-contents"><summary>In this guide</summary><nav aria-label="Mobile contents">${toc}</nav></details>
<article>${body}<footer class="footer">Detours is free and open source. <a href="#detours-user-guide">Back to top</a></footer></article>
</main></div>
</body></html>
`;
for (const match of html.matchAll(/href="#([^"]+)"/g)) {
  if (match[1] !== 'guide' && !ids.has(match[1])) throw new Error(`Broken anchor: ${match[1]}`);
}
const destination = new URL('USER_GUIDE.html', docs);
if (process.argv[2] === '--check') {
  if (readFileSync(destination, 'utf8') !== html) throw new Error('HTML guide is stale; regenerate it.');
  console.log('Guide is current; heading IDs, local links and image signatures checked.');
} else {
  if (process.argv.length > 2) throw new Error('Usage: node resources/scripts/render-user-guide.mjs [--check]');
  writeFileSync(destination, html);
  if (readFileSync(destination, 'utf8') !== html) throw new Error('Guide write verification failed.');
  console.log(`Rendered and read back ${destination.pathname}: ${headings.length} sections, ${html.length} bytes.`);
}
